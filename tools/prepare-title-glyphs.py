"""Build the eight title glyphs from Adobe's Source Han Sans Heavy (SIL OFL).

Usage: python tools/prepare-title-glyphs.py
Runtime SVGs and the original font stay outside the public source repository.
"""
from pathlib import Path
import hashlib
import json
import urllib.request
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "https://raw.githubusercontent.com/adobe-fonts/source-han-sans/release/OTF/SimplifiedChinese/SourceHanSansSC-Heavy.otf"
SHA256 = "6374b11bc4c2cd4bd7be1a1d64cf5047906c8a6a025c64e023c6792e50ba985e"
source = ROOT / ".data/sources/brand/SourceHanSansSC-Heavy.otf"
source.parent.mkdir(parents=True, exist_ok=True)
if not source.exists():
    with urllib.request.urlopen(SOURCE, timeout=90) as response:
        source.write_bytes(response.read())
assert hashlib.sha256(source.read_bytes()).hexdigest() == SHA256, "Font source changed"
font = TTFont(source)
glyphs = font.getGlyphSet()
mapping = font.getBestCmap()
manifest_path = ROOT / "assets/manifest.json"
manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
manifest = [entry for entry in manifest if not entry["id"].startswith("title-glyph-")]
for char in "明日方舟游城拓荒":
    pen = SVGPathPen(glyphs)
    glyphs[mapping[ord(char)]].draw(pen)
    name = f"title-glyph-{ord(char):x}.svg"
    relative = f"apps/web/public/assets/{name}"
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000">'
           f'<path transform="translate(0 880) scale(1 -1)" fill="#f1e5ca" '
           f'd="{pen.getCommands()}"/></svg>\n').encode("utf-8")
    destination = ROOT / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(svg)
    manifest.append({
        "id": name, "path": relative,
        "sourceFile": source.relative_to(ROOT).as_posix(),
        "sourceUrl": SOURCE, "sourceSha256": SHA256,
        "processing": f"Source Han Sans SC Heavy glyph U+{ord(char):04X}; native outline in a 1000-unit SVG, baseline 880; warm paper fill. Generated by tools/prepare-title-glyphs.py.",
        "rights": "Adobe Source Han Sans, SIL Open Font License 1.1; see assets/licenses/source-han-sans-OFL.txt.",
        "sha256": hashlib.sha256(svg).hexdigest(), "bytes": len(svg), "size": [1000, 1000],
    })
manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print("Prepared 8 vector title glyphs from the pinned Source Han Sans Heavy font.")
